// TuningAdvisor implements Module Q: Tuning Advisor
// Generates sysctl.conf patches based on workload type. Does NOT auto-apply.
type TuningAdvisor struct {
	mu       sync.RWMutex
	eventBus *eventbus.EventBus
}

func New(bus *eventbus.EventBus) *TuningAdvisor {
	return &TuningAdvisor{eventBus: bus}
}

// Suggestion represents a tuning suggestion.
type Suggestion struct {
	Parameter string
	Value     string
	Reason    string
	Current   string
}

// Analyze analyzes the system and generates tuning suggestions.
func (g *TuningAdvisor) Analyze(workloadType string, cpuCores int, memTotalGB float64) []Suggestion {
	var suggestions []Suggestion

	switch workloadType {
	case "streaming":
		suggestions = append(suggestions,
			Suggestion{"net.core.rmem_max", "16777216", "增大接收缓冲区，优化流媒体传输", ""},
			Suggestion{"net.core.wmem_max", "16777216", "增大发送缓冲区，优化流媒体传输", ""},
			Suggestion{"net.ipv4.tcp_rmem", "4096 87380 16777216", "TCP接收缓冲区自动调优", ""},
			Suggestion{"net.ipv4.tcp_wmem", "4096 65536 16777216", "TCP发送缓冲区自动调优", ""},
			Suggestion{"net.ipv4.tcp_tw_reuse", "1", "复用TIME_WAIT连接", ""},
		)
	case "database":
		suggestions = append(suggestions,
			Suggestion{"vm.swappiness", "1", "降低swap使用倾向，避免数据库性能下降", ""},
			Suggestion{"fs.file-max", fmt.Sprintf("%d", 2097152), "提高最大文件描述符数", ""},
			Suggestion{"kernel.sem", "250 32000 100 128", "增大信号量，支持更多并发连接", ""},
			Suggestion{"vm.dirty_ratio", "10", "降低脏页比例，减少写入突发", ""},
			Suggestion{"vm.dirty_background_ratio", "5", "后台刷脏页阈值", ""},
		)
	case "ai":
		suggestions = append(suggestions,
			Suggestion{"vm.swappiness", "10", "适度使用swap，避免OOM导致训练中断", ""},
			Suggestion{"fs.file-max", fmt.Sprintf("%d", 2097152), "提高最大文件描述符数", ""},
			Suggestion{"kernel.shmmax", fmt.Sprintf("%d", int64(64*1024*1024*1024)), "增大共享内存上限，支持大模型加载", ""},
			Suggestion{"vm.overcommit_memory", "1", "允许内存超分配，AI训练常用", ""},
		)
	case "web":
		suggestions = append(suggestions,
			Suggestion{"net.core.somaxconn", "65535", "增大连接队列，支持高并发", ""},
			Suggestion{"net.ipv4.tcp_max_syn_backlog", "65535", "增大SYN队列", ""},
			Suggestion{"net.ipv4.tcp_tw_reuse", "1", "复用TIME_WAIT连接", ""},
			Suggestion{"net.ipv4.ip_local_port_range", "10240 65535", "扩大本地端口范围", ""},
			Suggestion{"net.ipv4.tcp_fastopen", "3", "启用TCP Fast Open", ""},
		)
	}

	// CPU-related suggestions
	if cpuCores > 0 {
		// Suggest based on CPU count
		if cpuCores >= 8 {
			suggestions = append(suggestions,
				Suggestion{"net.core.netdev_max_backlog", fmt.Sprintf("%d", cpuCores*1000), "网卡接收队列，按核心数调优", ""})
		}
	}

	// Memory-related suggestions
	if memTotalGB > 0 {
		if memTotalGB < 2 {
			suggestions = append(suggestions,
				Suggestion{"vm.swappiness", "60", "低内存服务器适度使用swap", ""})
		}
	}

	return suggestions
}

// GeneratePatch generates a sysctl.conf patch from suggestions.
func (g *TuningAdvisor) GeneratePatch(suggestions []Suggestion) string {
	var builder strings.Builder
	builder.WriteString("# ServerGuard Tuning Suggestions\n")
	builder.WriteString("# Generated by Tuning Advisor - Review before applying\n")
	builder.WriteString("# DO NOT apply automatically without user confirmation\n\n")

	for _, s := range suggestions {
		builder.WriteString(fmt.Sprintf("# %s\n", s.Reason))
		builder.WriteString(fmt.Sprintf("%s = %s\n\n", s.Parameter, s.Value))
	}

	return builder.String()
}

// Notify publishes tuning suggestions as alerts.
func (g *TuningAdvisor) Notify(suggestions []Suggestion, workloadType string) {
	if len(suggestions) == 0 {
		return
	}

	var details strings.Builder
	for _, s := range suggestions {
		details.WriteString(fmt.Sprintf("- %s = %s (%s)\n", s.Parameter, s.Value, s.Reason))
	}

	g.eventBus.PublishAlert(types.AlertInfo, "tuning",
		fmt.Sprintf("调优建议: %s 工作负载", workloadType),
		fmt.Sprintf("基于 %s 工作负载生成 %d 条调优建议（需用户审核后应用，不自动执行）:\n%s",
			workloadType, len(suggestions), details.String()),
		"tuning-001")
}

